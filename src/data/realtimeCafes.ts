export interface RealtimeStatusResult {
  isOpenNow: boolean;
  isOpeningSoon: boolean;
  isClosingSoon: boolean;
  statusLabel: string;
  statusColor: 'green' | 'amber' | 'red' | 'blue';
  detailMessage: string;
}

/**
 * Computes live open/closing status based on the current time (WIB UTC+7).
 */
export function getCafeRealtimeStatus(
  cafe: RealtimeCafeRecommendation,
  overrideNow?: Date
): RealtimeStatusResult {
  if (cafe.statusBadge === 'segera_buka') {
    return {
      isOpenNow: false,
      isOpeningSoon: false,
      isClosingSoon: false,
      statusLabel: 'Segera Buka (Coming Soon)',
      statusColor: 'blue',
      detailMessage: cafe.openingDateEstimate || 'Sedang proses fitting interior & kurasi menu'
    };
  }

  const now = overrideNow || new Date();
  const currentHours = now.getHours();
  const currentMinutes = now.getMinutes();
  const currentTotalMins = currentHours * 60 + currentMinutes;

  const [openH, openM] = cafe.openTime.split(':').map(Number);
  const [closeH, closeM] = cafe.closeTime.split(':').map(Number);

  const openTotalMins = openH * 60 + openM;
  let closeTotalMins = closeH * 60 + closeM;

  // Handle cafes closing past midnight (e.g. 00:00 or 01:00)
  if (closeTotalMins <= openTotalMins) {
    closeTotalMins += 24 * 60;
  }

  let adjustedCurrentTotalMins = currentTotalMins;
  if (currentTotalMins < openTotalMins && closeTotalMins > 24 * 60 && currentTotalMins < (closeTotalMins - 24 * 60)) {
    adjustedCurrentTotalMins += 24 * 60;
  }

  // Check if open now
  const isOpen = adjustedCurrentTotalMins >= openTotalMins && adjustedCurrentTotalMins < closeTotalMins;

  if (isOpen) {
    const minsUntilClose = closeTotalMins - adjustedCurrentTotalMins;
    if (minsUntilClose <= 45) {
      return {
        isOpenNow: true,
        isOpeningSoon: false,
        isClosingSoon: true,
        statusLabel: 'Segera Tutup',
        statusColor: 'amber',
        detailMessage: `Tutup dalam ${minsUntilClose} menit (Jam ${cafe.closeTime} WIB)`
      };
    }
    return {
      isOpenNow: true,
      isOpeningSoon: false,
      isClosingSoon: false,
      statusLabel: 'Buka Sekarang',
      statusColor: 'green',
      detailMessage: `Buka sampai jam ${cafe.closeTime} WIB`
    };
  } else {
    // Check if opening soon (within 90 minutes before opening)
    const minsUntilOpen = openTotalMins - currentTotalMins;
    if (minsUntilOpen > 0 && minsUntilOpen <= 90) {
      return {
        isOpenNow: false,
        isOpeningSoon: true,
        isClosingSoon: false,
        statusLabel: 'Akan Segera Buka',
        statusColor: 'amber',
        detailMessage: `Buka jam ${cafe.openTime} WIB (${minsUntilOpen} menit lagi)`
      };
    }

    return {
      isOpenNow: false,
      isOpeningSoon: false,
      isClosingSoon: false,
      statusLabel: 'Tutup Saat Ini',
      statusColor: 'red',
      detailMessage: `Buka kembali jam ${cafe.openTime} WIB (${cafe.openDays})`
    };
  }
}

/**
 * Calculates geographic distance in kilometers using the Haversine formula
 */
export function calculateDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const distance = R * c;
  return Math.round(distance * 10) / 10; // Round to 1 decimal place
}

